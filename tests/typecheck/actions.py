def check_search_action() -> None:
    search = coin.SoSearchAction()
    assert_type(search.getNode(), coin.SoNode | None)
    assert_type(search.getType(coin.intp()), coin.SoType)
    assert_type(search.getName(), coin.SbName)
    assert_type(search.getFind(), int)
    assert_type(search.getInterest(), int)
    assert_type(search.isSearchingAll(), bool)
    assert_type(search.getPath(), coin.SoPath | None)
    assert_type(search.getPaths(), coin.SoPathList)
    assert_type(search.isFound(), bool)

    search.setNode(coin.SoCube())
    search.setType(coin.SoCube.getClassTypeId())
    search.setName(coin.SbName("cube"))
    search.setFind(coin.SoSearchAction.ALL)
    search.setInterest(coin.SoSearchAction.LAST)
    search.setSearchingAll(True)
    search.setFound()
    search.addPath(coin.SoPath())
    search.reset()


def check_geometry_actions() -> None:
    viewport = coin.SbViewportRegion()
    root = coin.SoSeparator()

    bbox = coin.SoGetBoundingBoxAction(viewport)
    assert_type(bbox.getViewportRegion(), coin.SbViewportRegion)
    assert_type(bbox.getBoundingBox(), coin.SbBox3f)
    assert_type(bbox.getXfBoundingBox(), coin.SbXfBox3f)
    assert_type(bbox.getCenter(), coin.SbVec3f)
    assert_type(bbox.getResetPath(), coin.SoPath | None)
    assert_type(bbox.isResetPath(), bool)
    assert_type(bbox.isResetBefore(), bool)
    assert_type(bbox.isCenterSet(), bool)
    bbox.apply(root)
    bbox.extendBy(coin.SbBox3f())
    bbox.extendBy(coin.SbXfBox3f())

    matrix = coin.SoGetMatrixAction(viewport)
    assert_type(matrix.getViewportRegion(), coin.SbViewportRegion)
    assert_type(matrix.getMatrix(), coin.SbMatrix)
    assert_type(matrix.getInverse(), coin.SbMatrix)
    assert_type(matrix.getTextureMatrix(), coin.SbMatrix)
    assert_type(matrix.getTextureInverse(), coin.SbMatrix)
    matrix.apply(root)

    primitive = coin.SoGetPrimitiveCountAction()
    assert_type(primitive.getTriangleCount(), int)
    assert_type(primitive.getLineCount(), int)
    assert_type(primitive.getPointCount(), int)
    assert_type(primitive.containsNoPrimitives(), bool)
    assert_type(primitive.containsNonTriangleShapes(), bool)
    assert_type(primitive.canApproximateCount(), bool)
    primitive.apply(root)


def check_event_pick_and_write_actions() -> None:
    viewport = coin.SbViewportRegion()
    root = coin.SoSeparator()

    event = coin.SoHandleEventAction(viewport)
    assert_type(event.getViewportRegion(), coin.SbViewportRegion)
    assert_type(event.getEvent(), coin.SoEvent | None)
    assert_type(event.isHandled(), bool)
    assert_type(event.getGrabber(), coin.SoNode | None)
    assert_type(event.getPickRoot(), coin.SoNode | None)
    assert_type(event.getPickedPoint(), coin.SoPickedPoint | None)
    assert_type(event.getPickedPointList(), coin.SoPickedPointList)
    event.setEvent(coin.SoKeyboardEvent())
    event.setGrabber(root)
    event.setPickRoot(root)
    event.setHandled()
    event.releaseGrabber()

    pick = coin.SoRayPickAction(viewport)
    assert_type(pick.getPickedPoint(), coin.SoPickedPoint | None)
    assert_type(pick.getPickedPoint(0), coin.SoPickedPoint | None)
    assert_type(pick.getPickedPointList(), coin.SoPickedPointList)
    assert_type(pick.getViewVolume(), coin.SbViewVolume)
    assert_type(pick.getLine(), coin.SbLine)
    assert_type(pick.hasWorldSpaceRay(), bool)
    pick.setPoint(coin.SbVec2s(0, 0))
    pick.setNormalizedPoint(coin.SbVec2f(0.0, 0.0))
    pick.setRay(coin.SbVec3f(), coin.SbVec3f(0.0, 0.0, -1.0))
    pick.setPickAll(True)

    output = coin.SoOutput()
    write = coin.SoWriteAction(output)
    assert_type(write.getOutput(), coin.SoOutput)
    assert_type(write.continueToApply(root), None)


