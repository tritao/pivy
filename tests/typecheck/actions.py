from typing import assert_type

from pivy import coin


def check_action_application() -> None:
    root = coin.SoSeparator()
    cube = coin.SoCube()
    root.addChild(cube)
    path = coin.SoPath(root)
    path.append(0)
    paths = coin.SoPathList()
    paths.append(path)

    action = coin.SoCallbackAction()
    assert_type(action.apply(root), None)
    assert_type(action.apply(path), None)
    assert_type(action.apply(paths), None)
    assert_type(action.apply(paths, True), None)
    assert_type(action.hasTerminated(), bool)
    assert_type(action.getState(), coin.SoState)
    assert_type(action.getCurPath(), coin.SoPath)
    assert_type(action.getCurPathTail(), coin.SoNode)
    assert_type(action.getNodeAppliedTo(), coin.SoNode | None)
    assert_type(action.getPathAppliedTo(), coin.SoPath | None)
    assert_type(action.getPathListAppliedTo(), coin.SoPathList | None)
    assert_type(action.getOriginalPathListAppliedTo(), coin.SoPathList | None)

    action.pushCurPath()
    action.pushCurPath(0, cube)
    action.popPushCurPath(0)
    action.popCurPath()
    action.popCurPath(coin.SoAction.NODE)
    action.switchToNodeTraversal(root)
    action.switchToPathTraversal(path)


